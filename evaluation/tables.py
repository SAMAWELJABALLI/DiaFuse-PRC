"""Tables (CSV + LaTeX + Markdown) from results/metrics/*.csv and tables/statistical_tests.csv.
The Table 5 mapping is taken explicitly from configs/protocol.json ("table5"), never from column order:
Accuracy on S0, S3, S6 and exact match on (S0,S1), (S0,S2), (S5AR,S5)."""
import csv
import glob
import json
import os
import shutil

import numpy as np

# Manuscript labels for B11 and B12. DiaFuse-PRC++ systems carry "++": PPB-FINAL is NOT the manuscript's B12'
# (never executed; see models/B12_prime_diafuse_setting_B_lora/README.md).
LABEL = {"B11": "B11 Robust + calibrated (Shao et al. style)", "B12": "B12 DiaFuse-PRC (Setting A)",
         "PPA-FINAL": "B12++ DiaFuse-PRC++ (Setting A)", "PPB-FINAL": "B12'++ DiaFuse-PRC++ (Setting B, LoRA)",
         "ARCH-B0": "B0 Arabic-only (archived run, 3 seeds)", "ARCH-B6": "B6 static concatenation (archived run, 3 seeds)",
         "ARCH-B10": "B10 SharpReCL-style (archived run, 3 seeds)", "ARCH-B11": "B11 (archived run, 3 seeds)", "ARCH-B12": "B12 (archived run, 3 seeds)"}
CHAIN = ["S0", "S1", "S2", "S3", "S4", "S5", "S6"]


def load_summary(results_dir):
    S = {}
    p = os.path.join(results_dir, "metrics", "summary_metrics.csv")
    if os.path.exists(p):
        for r in csv.DictReader(open(p)):
            S[(r["system"], r["stage"], r["metric"])] = (float(r["mean"]), float(r["sd"]), int(r["n_seeds"]))
    return S


def tex_escape(s):
    return str(s).replace("&", "\\&").replace("_", "\\_").replace("%", "\\%").replace("±", "$\\pm$").replace("Δ", "$\\Delta$")


def write_table(path_base, header, rows, caption=""):
    with open(path_base + ".csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(header); w.writerows(rows)
    with open(path_base + ".md", "w") as f:
        f.write("| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n")
        for r in rows:
            f.write("| " + " | ".join(str(x) for x in r) + " |\n")
    with open(path_base + ".tex", "w") as f:
        f.write("% generated by evaluation/tables.py - do not edit by hand\n")
        f.write("\\begin{table}[t]\n\\centering\n\\scriptsize\n")
        if caption:
            f.write(f"\\caption{{{tex_escape(caption)}}}\n")
        f.write("\\begin{tabular}{@{}l" + "c" * (len(header) - 1) + "@{}}\n\\toprule\n")
        f.write(" & ".join(tex_escape(h) for h in header) + " \\\\ \\midrule\n")
        for r in rows:
            f.write(" & ".join(tex_escape(x) for x in r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def fmt(S, sysn, stage, met="mf1", sd=True):
    v = S.get((sysn, stage, met))
    if v is None:
        return "n/a"
    return f"{100 * v[0]:.1f} ± {100 * v[1]:.1f}" if sd else f"{100 * v[0]:.1f}"


def write_all(results_dir, tables_dir, pp_out, P, run_dir):
    os.makedirs(tables_dir, exist_ok=True)
    S = load_summary(results_dir)
    systems = sorted({k[0] for k in S})
    core = [s for s in ("B11", "B12", "PPA-FINAL", "PPB-FINAL") if s in systems]
    # ---- main results S0-S6
    hdr = ["Model", "seeds"] + CHAIN + ["mean S0-S6", "mean S3-S6"]
    rows = []
    for s in core:
        n = S.get((s, "S0", "mf1"), (0, 0, 0))[2]
        m = [S[(s, st, "mf1")][0] for st in CHAIN if (s, st, "mf1") in S]
        rows.append([LABEL.get(s, s), n] + [fmt(S, s, st) for st in CHAIN] +
                    [f"{100 * np.mean(m):.2f}" if len(m) == 7 else "n/a", f"{100 * np.mean(m[3:]):.2f}" if len(m) == 7 else "n/a"])
    write_table(os.path.join(tables_dir, "main_results"), hdr, rows, "Macro-F1 (%) along the test chain, mean ± sd over seeds")
    # ---- final comparison with Delta vs B11 and the protocol tests
    tests = {}
    tp = os.path.join(tables_dir, "statistical_tests.csv")
    if os.path.exists(tp):
        for r in csv.DictReader(open(tp)):
            tests[(r["comparison"], r["stage"])] = r
    ver = json.load(open(os.path.join(tables_dir, "verdict.json"))).get("verdicts", {}) if os.path.exists(os.path.join(tables_dir, "verdict.json")) else {}
    hdr2 = ["Row"] + CHAIN + ["mean Δ", "median Δ", "#Δ>0", "#Δ>1", "#Δ>2"]
    rows2 = [[LABEL.get(s, s)] + [fmt(S, s, st) for st in CHAIN] + [""] * 5 for s in core]
    for pp in ("PPA-FINAL", "PPB-FINAL", "B12"):
        if pp in core and "B11" in core:
            d = [100 * (S[(pp, st, "mf1")][0] - S[("B11", st, "mf1")][0]) for st in CHAIN]
            cells = []
            for st, x in zip(CHAIN, d):
                t = tests.get((f"{pp} vs B11", st))
                mark = "*" if t and t["significant"] == "True" else ""
                cells.append(f"{x:+.2f}{mark}")
            rows2.append([f"Δ {pp} − B11"] + cells + [f"{np.mean(d):+.2f}", f"{np.median(d):+.2f}", int((np.array(d) > 0).sum()),
                                                      int((np.array(d) > 1).sum()), int((np.array(d) > 2).sum())])
    write_table(os.path.join(tables_dir, "final_comparison"), hdr2, rows2,
                "B11 vs B12 vs DiaFuse-PRC++ (macro-F1 %); * = decision rule of the protocol satisfied (Holm-adjusted paired bootstrap p<0.05 and Δ > larger seed sd)")
    for name in ("final_comparison.csv", "final_comparison.tex", "final_comparison.md", "main_results.csv", "main_results.tex"):
        shutil.copy(os.path.join(tables_dir, name), os.path.join(run_dir, name))
    with open(os.path.join(tables_dir, "final_comparison.md"), "a") as f:
        f.write("\n")
        for pp, v in ver.items():
            msg = {"OUTPERFORMS": "DiaFuse-PRC++ outperforms B11", "PARTIAL": "DiaFuse-PRC++ outperforms B11 on some stages only",
                   "DOES_NOT_OUTPERFORM": "DiaFuse-PRC++ does not outperform B11"}[v["verdict"]]
            f.write(f"RESULT ({pp}): {msg} (stages won: {v['stages_won']}; stages lost: {v['stages_lost']})\n\n")
    # ---- Table 5 (explicit mapping)
    t5 = P["table5"]; sys5 = [s for s in ("ARCH-B0", "ARCH-B6", "ARCH-B10", "B11", "B12", "PPA-FINAL", "PPB-FINAL") if s in systems]
    hdr5 = ["System"] + [f"Acc {lab}" for lab, _ in t5["accuracy"]] + [f"EM {lab}" for lab, _, _ in t5["em"]] + [f"M-F1 {lab}" for lab, _ in t5["accuracy"]]
    stage_of = {v: k for k, v in P["stages"].items()}
    rows5 = []
    for s in sys5:
        r = [LABEL.get(s, s)]
        r += [fmt(S, s, lab, "acc", sd=False) for lab, _ in t5["accuracy"]]
        r += [fmt(S, s, stage_of[st], "em", sd=False) for _, st, _ in t5["em"]]
        r += [fmt(S, s, lab, "mf1", sd=False) for lab, _ in t5["accuracy"]]
        rows5.append(r)
    write_table(os.path.join(tables_dir, "table5"), hdr5, rows5,
                "Table 5 format: accuracy (%) on S0, S3, S6 and exact match (%) on (S0,S1), (S0,S2), (S5AR,S5); mean over seeds")
    # ---- ablations
    hdrA = ["Setting", "Ablation", "seeds"] + [f"Δ {st}" for st in CHAIN] + ["Δ mean S0-S6", "Δ mean S3-S6"]
    rowsA = []
    for setting in ("A", "B"):
        fin = f"PP{setting}-FINAL"
        if fin not in systems:
            continue
        for s in [x for x in systems if x.startswith(f"PP{setting}-ABL-")]:
            if not all((s, st, "mf1") in S for st in CHAIN):
                continue
            d = [100 * (S[(fin, st, "mf1")][0] - S[(s, st, "mf1")][0]) for st in CHAIN]
            rowsA.append([setting, s.split("-ABL-")[1], S[(s, "S0", "mf1")][2]] + [f"{x:+.2f}" for x in d] + [f"{np.mean(d):+.2f}", f"{np.mean(d[3:]):+.2f}"])
    write_table(os.path.join(tables_dir, "ablations"), hdrA, rowsA, "Ablations: Δ = selected model − ablated model (macro-F1 points; positive = component helps)")
    # ---- seed-level results and selection
    src = os.path.join(results_dir, "metrics", "seed_results.csv")
    if os.path.exists(src):
        shutil.copy(src, os.path.join(tables_dir, "seed_results.csv"))
    sel_rows = []
    for p in sorted(glob.glob(os.path.join(pp_out, "dev", "*", "*.json"))):
        r = json.load(open(p))
        sel_rows.append([r.get("config"), r.get("family"), r.get("seed"), r.get("dev"), r.get("trainable_params"), round(r.get("minutes", 0) or 0, 2)])
    with open(os.path.join(tables_dir, "selection_results.csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["config", "family", "seed", "dev_macro_f1", "trainable_params", "minutes"]); w.writerows(sel_rows)


def export_system(results_dir, preds_dir, system, out_dir):
    """results/<B11|B12|selected_model/...|ablations/...>: per-seed metrics and predictions of one system."""
    src = os.path.join(results_dir, "metrics", "seed_results.csv")
    if not os.path.isdir(os.path.join(preds_dir, system)) or not os.path.exists(src):
        return
    os.makedirs(out_dir, exist_ok=True)
    with open(src) as f, open(os.path.join(out_dir, "seed_metrics.csv"), "w", newline="") as g:
        r = csv.reader(f); w = csv.writer(g); hdr = next(r); w.writerow(hdr)
        for row in r:
            if row[0] == system:
                w.writerow(row)
    dst = os.path.join(out_dir, "predictions")
    if not os.path.exists(dst):
        shutil.copytree(os.path.join(preds_dir, system), dst)
